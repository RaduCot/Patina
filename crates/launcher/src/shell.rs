//! Opening things, and the login autostart entry.

use std::path::{Path, PathBuf};
use std::process::Command;

use windows::Win32::Foundation::ERROR_CANCELLED;
use windows::Win32::Storage::EnhancedStorage::PKEY_Link_TargetParsingPath;
use windows::Win32::UI::Shell::{IShellItem2, KF_FLAG_DEFAULT, SHCreateItemFromParsingName, SHGetKnownFolderPath};
use windows::core::GUID;
use windows::Win32::System::Com::{COINIT_APARTMENTTHREADED, COINIT_DISABLE_OLE1DDE, CoInitializeEx, CoTaskMemFree};
use windows::Win32::System::Registry::{HKEY_CURRENT_USER, REG_SZ, RegDeleteKeyValueW, RegSetKeyValueW};
use windows::Win32::UI::Shell::Common::ITEMIDLIST;
use windows::Win32::UI::Shell::{
    SEE_MASK_FLAG_NO_UI, SEE_MASK_INVOKEIDLIST, SHELLEXECUTEINFOW, SHParseDisplayName, ShellExecuteExW, ShellExecuteW,
};
use windows::Win32::UI::WindowsAndMessaging::SW_SHOWNORMAL;
use windows::core::{HSTRING, PCWSTR, w};

/// ShellExecute on a throwaway thread: it can block on slow handlers, and it
/// wants its own STA. `params` is passed through (used by reveal).
fn shell_open(file: String, params: Option<String>) {
    std::thread::spawn(move || unsafe {
        let _ = CoInitializeEx(None, COINIT_APARTMENTTHREADED | COINIT_DISABLE_OLE1DDE);
        let file_h = HSTRING::from(file.as_str());
        let params_h = params.as_deref().map(HSTRING::from);
        let r = ShellExecuteW(
            None,
            w!("open"),
            &file_h,
            params_h.as_ref().map_or(PCWSTR::null(), |p| PCWSTR(p.as_ptr())),
            PCWSTR::null(),
            SW_SHOWNORMAL,
        );
        if (r.0 as isize) <= 32 {
            patina_ui::log::line("launcher", &format!("could not open {file} (code {})", r.0 as isize));
        }
    });
}

/// Any Apps-folder entry, desktop or Store, by its parsing name.
pub fn launch_app(id: &str) {
    shell_open(format!(r"shell:AppsFolder\{id}"), None);
}

pub fn open_path(path: &Path) {
    shell_open(path.to_string_lossy().into_owned(), None);
}

/// A URI (ms-settings:...) or a command with optional parameters.
pub fn open_target(target: &str, params: Option<&str>) {
    shell_open(target.to_string(), params.map(str::to_string));
}

/// Open the containing folder with the item selected.
pub fn reveal(path: &Path) {
    shell_open("explorer.exe".into(), Some(format!("/select,\"{}\"", path.display())));
}

/// Run elevated (Windows shows the UAC prompt). The "runas" verb is invoked
/// on the shell ITEM, not a path, so a Start-menu app - whose id is a
/// shortcut or a known-folder path, not an exe - elevates exactly as Start's
/// own "Run as administrator" does. Declining the prompt is not an error.
fn invoke_verb(target: String, verb: &'static str) {
    std::thread::spawn(move || unsafe {
        let _ = CoInitializeEx(None, COINIT_APARTMENTTHREADED | COINIT_DISABLE_OLE1DDE);
        let mut pidl: *mut ITEMIDLIST = std::ptr::null_mut();
        if let Err(e) = SHParseDisplayName(&HSTRING::from(target.as_str()), None, &mut pidl, 0, None) {
            patina_ui::log::line("launcher", &format!("{verb}: cannot resolve {target}: {e}"));
            return;
        }
        let verb_h = HSTRING::from(verb);
        let mut sei = SHELLEXECUTEINFOW {
            cbSize: std::mem::size_of::<SHELLEXECUTEINFOW>() as u32,
            fMask: SEE_MASK_INVOKEIDLIST | SEE_MASK_FLAG_NO_UI,
            lpVerb: PCWSTR(verb_h.as_ptr()),
            lpIDList: pidl as *mut _,
            nShow: SW_SHOWNORMAL.0,
            ..Default::default()
        };
        if let Err(e) = ShellExecuteExW(&mut sei) {
            if e.code() != ERROR_CANCELLED.to_hresult() {
                patina_ui::log::line("launcher", &format!("{verb} {target} failed: {e}"));
            }
        }
        CoTaskMemFree(Some(pidl as *const _));
    });
}

pub fn run_app_as_admin(id: &str) {
    invoke_verb(format!(r"shell:AppsFolder\{id}"), "runas");
}

pub fn run_path_as_admin(path: &Path) {
    invoke_verb(path.to_string_lossy().into_owned(), "runas");
}

/// Windows' "Open with" chooser for a file.
pub fn open_with(path: &Path) {
    invoke_verb(path.to_string_lossy().into_owned(), "openas");
}

/// The shell's Properties sheet (it lives in Patina's process, which stays running).
pub fn properties(target: String) {
    invoke_verb(target, "properties");
}

/// Where an Apps-folder desktop app actually lives. Its id is a path: either
/// absolute, or under a known folder - "{6D809377-...}\7-Zip\7zFM.exe" is
/// Program Files\7-Zip\7zFM.exe. Store apps (AUMIDs, with '!') and
/// generated ids ("Microsoft.AutoGenerated.{...}") have no file to show.
pub fn app_path(id: &str) -> Option<PathBuf> {
    let path = if let Some(rest) = id.strip_prefix('{') {
        let (guid, tail) = rest.split_once('}')?;
        let guid = GUID::try_from(guid).ok()?;
        let base = unsafe {
            let p = SHGetKnownFolderPath(&guid, KF_FLAG_DEFAULT, None).ok()?;
            let s = p.to_string().ok();
            CoTaskMemFree(Some(p.0 as *const _));
            s?
        };
        PathBuf::from(base).join(tail.trim_start_matches('\\'))
    } else if Path::new(id).is_absolute() {
        PathBuf::from(id)
    } else if !id.contains('!') {
        // A shortcut with its own app id (Brave, Android Studio, AnyDesk...):
        // the id is no path, but the Apps-folder item knows its link target -
        // the same property Start's own "Open file location" reads.
        return link_target(id);
    } else {
        return None;
    };
    path.exists().then_some(path)
}

fn link_target(id: &str) -> Option<PathBuf> {
    unsafe {
        // Harmless if this thread already has COM (the UI thread does).
        let _ = CoInitializeEx(None, COINIT_APARTMENTTHREADED);
        let item: IShellItem2 = SHCreateItemFromParsingName(&HSTRING::from(format!(r"shell:AppsFolder\{id}")), None).ok()?;
        let s = item.GetString(&PKEY_Link_TargetParsingPath).ok()?;
        let target = s.to_string().ok();
        CoTaskMemFree(Some(s.0 as *const _));
        let p = PathBuf::from(target?);
        p.exists().then_some(p)
    }
}

/// A terminal in `dir`: WezTerm (the one this setup uses), else Windows
/// Terminal, else PowerShell in its own console.
pub fn open_terminal(dir: &Path) {
    let dir = dir.to_path_buf();
    std::thread::spawn(move || {
        let on_path = |exe: &str| {
            std::env::var_os("PATH")
                .and_then(|p| std::env::split_paths(&p).map(|d| d.join(exe)).find(|c| c.exists()))
        };
        let wezterm = on_path("wezterm.exe")
            .or_else(|| Some(PathBuf::from(r"C:\Program Files\WezTerm\wezterm.exe")).filter(|p| p.exists()));
        let started = match wezterm {
            Some(w) => Command::new(w).args(["start", "--cwd"]).arg(&dir).spawn().is_ok(),
            None => false,
        } || on_path("wt.exe").is_some_and(|wt| Command::new(wt).arg("-d").arg(&dir).spawn().is_ok())
            || Command::new("powershell.exe").arg("-NoExit").current_dir(&dir).spawn().is_ok();
        if !started {
            patina_ui::log::line("launcher", &format!("could not open a terminal in {}", dir.display()));
        }
    });
}

/// `--probe-verb <verb> <target>`: invoke a verb the same way (harmless with "open").
pub fn probe_verb(verb: &'static str, target: &str) {
    invoke_verb(target.to_string(), verb);
    std::thread::sleep(std::time::Duration::from_secs(3)); // let the thread finish before exit
}

#[cfg(test)]
mod tests {
    use super::app_path;

    #[test]
    fn known_folder_ids_resolve_to_real_files() {
        // FOLDERID_System + cmd.exe exists on every Windows install.
        let p = app_path(r"{1AC14E77-02E7-4E5D-B744-2EB1AE5198B7}\cmd.exe").expect("System32 cmd.exe");
        assert!(p.ends_with("cmd.exe") && p.exists());
    }

    #[test]
    fn store_apps_and_unknown_ids_have_no_file() {
        // Store apps (AUMIDs) have no file to show.
        assert!(app_path("windows.immersivecontrolpanel_cw5n1h2txyewy!microsoft.windows.immersivecontrolpanel").is_none());
        // An id the Apps folder doesn't know, and a path that isn't there.
        // (Real "Microsoft.AutoGenerated.{...}" ids DO resolve, through their
        // shortcut's link target - so this must be one that doesn't exist.)
        assert!(app_path("Microsoft.AutoGenerated.{00000000-0000-0000-0000-000000000000}").is_none());
        assert!(app_path(r"{1AC14E77-02E7-4E5D-B744-2EB1AE5198B7}\no-such-program.exe").is_none());
    }
}

const RUN_KEY: PCWSTR = w!(r"Software\Microsoft\Windows\CurrentVersion\Run");
const RUN_NAME: PCWSTR = w!("Patina Launcher");

pub fn set_autostart(on: bool) -> windows::core::Result<()> {
    unsafe {
        if on {
            let exe = std::env::current_exe().map_err(|_| windows::core::Error::from_thread())?;
            let cmd = HSTRING::from(format!("\"{}\" --background", exe.display()));
            let bytes = std::slice::from_raw_parts(cmd.as_ptr() as *const u8, (cmd.len() + 1) * 2);
            RegSetKeyValueW(HKEY_CURRENT_USER, RUN_KEY, RUN_NAME, REG_SZ.0, Some(bytes.as_ptr() as *const _), bytes.len() as u32)
                .ok()
        } else {
            RegDeleteKeyValueW(HKEY_CURRENT_USER, RUN_KEY, RUN_NAME).ok()
        }
    }
}
